#!/usr/bin/env python3
"""
AnyRB — inline the dev sources into a single standalone HTML file.

    python3 app/build.py

Reads:
    app/index.html, app/styles.css,
    app/config.js, app/engine.js, app/optimize.js, app/stl.js, app/ui.js
Writes:
    anyrb/index.html   (primary double-clickable standalone build)
    app/standalone.html   (identical convenience copy)

The sources are ES modules (used by Node tests and the dev http server). The
build wraps each module in its own function scope and wires imports/exports
through a small module registry, so the resulting <script> is a classic
(non-module) script that works from file:// in Chrome and Safari.

Dependency-free (stdlib only). Verifies the generated JS with `node --check`.
"""

import pathlib
import re
import subprocess
import sys
import tempfile

APP = pathlib.Path(__file__).resolve().parent
REPO = APP.parent

SOURCES = [
    ("config", APP / "config.js"),
    ("engine", APP / "engine.js"),
    ("optimize", APP / "optimize.js"),
    ("stl", APP / "stl.js"),
    ("aicore", APP / "aicore.js"),
    ("ai", APP / "ai.js"),
    ("product_render", APP / "product_render.js"),
    ("ui", APP / "ui.js"),
]

# ---------------------------------------------------------------------------
# Minimal ES-module → classic-script transform (works because we control the
# sources: imports are static, exports are declarations or `export { ... }`).
# ---------------------------------------------------------------------------
IMPORT_RE = re.compile(
    r"^import\s+(?:(\{[^}]*\})|\*\s+as\s+([A-Za-z_$][\w$]*))\s+from\s+['\"]([^'\"]+)['\"]\s*;?",
    re.MULTILINE | re.DOTALL,
)
EXPORT_DECL_RE = re.compile(
    r"^export\s+(?:(?:async\s+)?function\s*\*?\s*|(?:const|let|var|class)\s+)([A-Za-z_$][\w$]*)",
    re.MULTILINE,
)
EXPORT_STMT_RE = re.compile(r"^export\s*\{([^}]*)\}\s*;?", re.MULTILINE | re.DOTALL)


def module_key(path: str) -> str:
    base = path.rsplit("/", 1)[-1]
    return base[:-3] if base.endswith(".js") else base


def compile_module(name: str, src: str) -> str:
    imports = []
    for match in IMPORT_RE.finditer(src):
        named, star, path = match.group(1), match.group(2), match.group(3)
        key = module_key(path)
        if star:
            imports.append(f"const {star} = __modules.{key};")
        else:
            spec = named[1:-1].strip()
            imports.append(f"const {{{spec}}} = __modules.{key};")
    body = IMPORT_RE.sub("", src)

    exports = []

    def add_export(item: str):
        item = item.strip()
        if item and item not in exports:
            exports.append(item)

    for match in EXPORT_DECL_RE.finditer(body):
        add_export(match.group(1))
    for match in EXPORT_STMT_RE.finditer(body):
        for part in match.group(1).split(","):
            part = part.strip()
            if not part:
                continue
            if " as " in part:
                orig, alias = [p.strip() for p in part.split(" as ")]
                add_export(f"{alias}: {orig}")
            else:
                add_export(part)

    body = re.sub(
        r"(?m)^(\s*)export\s+(?=(?:async\s+)?(?:const|let|var|function|class)\b)",
        r"\1",
        body,
    )
    body = EXPORT_STMT_RE.sub("", body)
    body = re.sub(r"(?m)^(\s*)export\s*default\s+", r"\1", body)

    ret = "return { " + ", ".join(exports) + " };" if exports else ""
    return (
        f"__modules.{name} = (function () {{\n"
        + "\n".join(imports)
        + "\n"
        + body
        + "\n"
        + ret
        + "\n})();"
    )


def build_bundle() -> str:
    parts = []
    for name, path in SOURCES:
        src = path.read_text(encoding="utf-8")
        parts.append(f"/* ===== {path.name} ===== */\n" + compile_module(name, src))
    return (
        "<script>\n"
        "/* AnyRB standalone build — generated by app/build.py; do not edit. */\n"
        "/* In-silico demo. Not a certification tool. */\n"
        "(function () {\n"
        "'use strict';\n"
        "var __modules = {};\n"
        + "\n\n".join(parts)
        + "\nwindow.__ANYRB__ = __modules;\n"
        "})();\n"
        "</script>"
    )


def main() -> int:
    errors = []

    index_path = APP / "index.html"
    css_path = APP / "styles.css"
    html = index_path.read_text(encoding="utf-8")
    css = css_path.read_text(encoding="utf-8")

    # 1. inline CSS
    if '<link rel="stylesheet" href="styles.css">' not in html:
        errors.append("index.html: stylesheet link not found (expected exact tag)")
    html = html.replace('<link rel="stylesheet" href="styles.css">', "<style>\n" + css + "\n</style>")

    # 2. strip dev-only elements (module shell notice + the file:// hint script)
    html = re.sub(r'<script[^>]*data-dev-only[^>]*>[\s\S]*?</script>', "", html)
    html = re.sub(r'<div[^>]*class="dev-note"[^>]*>[\s\S]*?</div>', "", html)

    # 3. inline the module bundle in place of the module script tag
    if '<script type="module" src="ui.js"></script>' not in html:
        errors.append("index.html: module script tag not found (expected exact tag)")
    bundle = build_bundle()
    html = html.replace('<script type="module" src="ui.js"></script>', bundle)

    # 4. checks
    leftovers = []
    for token in ("export const", "export function", "export {", "from './", "from \"./", "<script type=\"module\""):
        if token in html:
            leftovers.append(token)
    if leftovers:
        errors.append("standalone HTML still contains module syntax: " + ", ".join(leftovers))
    for marker in ("data-dev-only", "styles.css", "ui.js\""):
        if marker in html:
            errors.append(f"standalone HTML still references dev artefact: {marker}")

    # 5. syntax check the generated classic script with node
    script_match = re.search(r"<script>\n/\* AnyRB standalone build[\s\S]*?</script>", html)
    if not script_match:
        errors.append("could not locate generated <script> block for syntax check")
    else:
        js = script_match.group(0)[len("<script>"): -len("</script>")]
        with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as tmp:
            tmp.write(js)
            tmp_path = tmp.name
        try:
            proc = subprocess.run(["node", "--check", tmp_path], capture_output=True, text=True)
            if proc.returncode != 0:
                errors.append("node --check failed on generated script:\n" + (proc.stderr or proc.stdout))
        except FileNotFoundError:
            print("warning: node not found — skipping generated-script syntax check")
        finally:
            pathlib.Path(tmp_path).unlink(missing_ok=True)

    if errors:
        print("BUILD FAILED", file=sys.stderr)
        for err in errors:
            print(" -", err, file=sys.stderr)
        return 1

    out_root = REPO / "index.html"
    out_copy = APP / "standalone.html"
    out_root.write_text(html, encoding="utf-8")
    out_copy.write_text(html, encoding="utf-8")
    kb = len(html.encode("utf-8")) / 1024
    print(f"BUILD OK — {kb:.1f} KiB standalone app")
    print(f"  primary : {out_root}   (double-click to open)")
    print(f"  copy    : {out_copy}")
    print(f"  modules : {', '.join(p.name for _, p in SOURCES)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
